/**
 * Select a behavior description from the matrix using deterministic hash
 *
 * @param tier - The ratio tier (veryLow/low/medium/high)
 * @param disposition - Customer disposition
 * @param customerId - Customer ID for deterministic selection
 * @returns Selected behavior description text
 */
export function selectBehaviorDescription(
  tier: RatioTier,
  disposition: Disposition,
  customerId: string
): string {
  const descriptions = BEHAVIOR_MATRIX[tier]?.[disposition];
  if (!descriptions || descriptions.length === 0) {
    return '你对他的底线没有明确判断。';
  }

  const index = hashString(customerId) % descriptions.length;
  return descriptions[index].text;
}

/**
 * Simple string hash for deterministic selection
 */
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash;
  }
  return Math.abs(hash);
}
